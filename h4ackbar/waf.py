@dataclass
class WAFResult:
    detected: list[str] = field(default_factory=list)
    evidence: list[str] = field(default_factory=list)
    tampers: list[str] = field(default_factory=list)

    def summary(self) -> str:
        if not self.detected:
            return "no waf detected"
        return f"waf={','.join(self.detected)}  tampers={','.join(self.tampers)}"


def detect(headers: dict[str, str], body: str, status: int = 0) -> WAFResult:
    """Passive WAF fingerprint from a single response."""
    hdr_blob = "\n".join(f"{k.lower()}:{v}" for k, v in (headers or {}).items())
    body_head = (body or "")[:4000].lower()
    res = WAFResult()

    for sig in WAF_CATALOG:
        hit = False
        for pat in sig.header_patterns:
            if re.search(pat, hdr_blob, re.I):
                res.evidence.append(f"{sig.name}: header /{pat}/")
                hit = True
                break
        if not hit:
            for pat in sig.body_patterns:
                if re.search(pat, body_head, re.I):
                    res.evidence.append(f"{sig.name}: body /{pat}/")
                    hit = True
                    break
        if not hit and status and status in sig.status_hits and not res.detected:
            # weak — only claim if no others matched
            continue
        if hit and sig.name not in res.detected:
            res.detected.append(sig.name)
            for t in sig.tampers:
                if t not in res.tampers:
                    res.tampers.append(t)
    return res


# ── quick access for UI ──────────────────────────────────────
def suggested_tampers(waf_name: str) -> list[str]:
    for sig in WAF_CATALOG:
        if sig.name == waf_name:
            return list(sig.tampers)
    return []


def all_waf_names() -> list[str]:
    return [s.name for s in WAF_CATALOG]
